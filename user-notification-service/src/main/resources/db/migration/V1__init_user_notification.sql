CREATE TABLE customer (
    id BIGINT PRIMARY KEY,
    full_name VARCHAR(160),
    phone VARCHAR(32),
    email VARCHAR(320),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE staff (
    id BIGINT PRIMARY KEY,
    full_name VARCHAR(160),
    phone VARCHAR(32),
    email VARCHAR(320),
    position VARCHAR(120),
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE staff_building (
    staff_id BIGINT NOT NULL REFERENCES staff(id) ON DELETE CASCADE,
    building_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (staff_id, building_id)
);
CREATE INDEX idx_staff_building_building ON staff_building(building_id, staff_id);

CREATE TABLE notification (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    type VARCHAR(80) NOT NULL,
    title VARCHAR(200) NOT NULL,
    content TEXT NOT NULL,
    ref_type VARCHAR(80),
    ref_id BIGINT,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notification_recipient_created ON notification(recipient_id, created_at DESC, id DESC);
CREATE INDEX idx_notification_unread ON notification(recipient_id, is_read);

CREATE TABLE device_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    token VARCHAR(4096) NOT NULL UNIQUE,
    platform VARCHAR(16) NOT NULL CHECK (platform IN ('IOS', 'ANDROID', 'WEB')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_device_token_account ON device_token(account_id);

CREATE TABLE processed_event (
    event_id UUID PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
