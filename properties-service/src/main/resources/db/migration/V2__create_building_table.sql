CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA public;

CREATE TABLE building (
    building_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    address VARCHAR(500) NOT NULL,
    ward_id BIGINT NOT NULL REFERENCES ward(ward_id),
    latitude NUMERIC(10, 8) NOT NULL,
    longitude NUMERIC(11, 8) NOT NULL,
    location public.GEOGRAPHY(POINT, 4326) GENERATED ALWAYS AS (
        public.ST_SetSRID(public.ST_MakePoint(longitude::double precision, latitude::double precision), 4326)::public.geography
    ) STORED NOT NULL,
    description TEXT,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    deleted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_building_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_building_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_building_ward_id ON building(ward_id);
CREATE INDEX idx_building_location_gist ON building USING GIST(location);
