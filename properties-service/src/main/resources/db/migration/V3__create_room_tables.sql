CREATE TABLE room_type (
    room_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE room (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES building(building_id),
    room_type_id BIGINT NOT NULL REFERENCES room_type(room_type_id),
    room_number VARCHAR(50) NOT NULL,
    max_capacity INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'VACANT',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_room_building_room_number UNIQUE (building_id, room_number),
    CONSTRAINT chk_room_max_capacity CHECK (max_capacity >= 1),
    CONSTRAINT chk_room_status CHECK (status IN ('VACANT', 'UPCOMING_VACANT', 'OCCUPIED', 'MAINTENANCE'))
);

CREATE INDEX idx_room_building_status ON room(building_id, status);
CREATE INDEX idx_room_room_type_id ON room(room_type_id);
