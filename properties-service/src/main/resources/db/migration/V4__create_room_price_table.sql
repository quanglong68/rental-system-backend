CREATE TABLE room_price (
    room_price_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES room(room_id),
    price NUMERIC(15, 0) NOT NULL,
    effective_from DATE NOT NULL,
    effective_to DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_room_price_non_negative CHECK (price >= 0),
    CONSTRAINT chk_room_price_date_order CHECK (effective_to IS NULL OR effective_to >= effective_from),
    CONSTRAINT ex_room_price_no_overlap EXCLUDE USING GIST (
        room_id WITH =,
        daterange(effective_from, effective_to, '[]') WITH &&
    )
);

CREATE INDEX idx_room_price_room_effective_from
    ON room_price(room_id, effective_from);
