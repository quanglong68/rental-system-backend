-- V1: schema auth_db (docs muc 7.3). Chi Flyway tao bang, Hibernate ddl-auto=validate.
-- Moi service mot database rieng, tham chieu cheo bang ID (khong FK xuyen service).
-- Thoi gian TIMESTAMPTZ (UTC), tien VND (khong co o service nay).

CREATE TABLE account (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(255) NOT NULL UNIQUE,
    password_hash    VARCHAR(255) NOT NULL,
    account_type     VARCHAR(20) NOT NULL,
    is_active        BOOLEAN NOT NULL DEFAULT TRUE,
    failed_login_count INTEGER NOT NULL DEFAULT 0,
    locked_until     TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE role (
    id   INTEGER PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE account_role (
    account_id BIGINT NOT NULL REFERENCES account (id),
    role_id    INTEGER NOT NULL REFERENCES role (id),
    PRIMARY KEY (account_id, role_id)
);

CREATE TABLE refresh_token (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id  BIGINT NOT NULL REFERENCES account (id),
    token_hash  VARCHAR(128) NOT NULL UNIQUE,
    expires_at  TIMESTAMPTZ NOT NULL,
    revoked_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_refresh_token_account ON refresh_token (account_id);

-- Transactional Outbox (docs muc 5.3): ghi cung giao dich nghiep vu, relay quet gui Kafka.
CREATE TABLE outbox_event (
    id           UUID PRIMARY KEY,
    topic        VARCHAR(100) NOT NULL,
    event_key    VARCHAR(255) NOT NULL,
    event_type   VARCHAR(100) NOT NULL,
    payload      JSONB NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ
);
CREATE INDEX idx_outbox_unpublished ON outbox_event (created_at) WHERE published_at IS NULL;

-- Idempotent consumer (docs muc 5.3): moi service co bang nay du chua nhan event.
CREATE TABLE processed_event (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
