package com.rental.contracttenant.dto;

import com.rental.contracttenant.entity.MoveOutRequest;
import com.rental.contracttenant.entity.MoveOutStatus;
import java.math.BigDecimal;
import java.time.Instant;
import java.time.LocalDate;
import lombok.AllArgsConstructor;
import lombok.Value;

@Value
@AllArgsConstructor
public class MoveOutRequestResponse {

    Long id;
    Long contractId;
    Long requestedBy;
    LocalDate requestDate;
    LocalDate expectedMoveOutDate;
    String reason;
    MoveOutStatus status;
    boolean autoGenerated;
    Instant readAt;
    Instant createdAt;
    BigDecimal refundAmount;
    BigDecimal deductionAmount;
    String deductionReason;
    String refundReceiptImageKey;
    String refundStatus;
    Instant refundedAt;

    public MoveOutRequestResponse(Long id, Long contractId, Long requestedBy, LocalDate requestDate,
            LocalDate expectedMoveOutDate, String reason, MoveOutStatus status, boolean autoGenerated,
            Instant readAt, Instant createdAt) {
        this(id, contractId, requestedBy, requestDate, expectedMoveOutDate, reason, status, autoGenerated,
                readAt, createdAt, null, null, null, null, null, null);
    }

    public static MoveOutRequestResponse from(MoveOutRequest req) {
        return new MoveOutRequestResponse(
                req.getId(),
                req.getContractId(),
                req.getRequestedBy(),
                req.getRequestDate(),
                req.getExpectedMoveOutDate(),
                req.getReason(),
                req.getStatus(),
                req.isAutoGenerated(),
                req.getReadAt(),
                req.getCreatedAt(),
                req.getRefundAmount(),
                req.getDeductionAmount(),
                req.getDeductionReason(),
                req.getRefundReceiptImageKey(),
                req.getRefundStatus(),
                req.getRefundedAt()
        );
    }
}
