-- Occupants of a contract (spec 9.4 "Quản lý người ở").
-- Rows are never deleted: a tenant leaving is recorded with left_at so Billing can prorate by day.
-- contract_id is an intra-service reference and therefore carries a real foreign key.
-- customer_id is a cross-service reference to the User service: NO foreign key (docs: cross-service IDs are scalar).
CREATE TABLE contract_tenant (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id       BIGINT NOT NULL REFERENCES contract(id),
    customer_id       BIGINT NOT NULL,
    joined_at         DATE NOT NULL,
    left_at           DATE,
    is_representative BOOLEAN NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- An occupant may not leave before they joined. left_at IS NULL means still occupying.
    CONSTRAINT contract_tenant_dates_check CHECK (left_at IS NULL OR left_at >= joined_at)
);

-- Occupant list for one contract (move-out, billing per contract).
CREATE INDEX idx_contract_tenant_contract ON contract_tenant(contract_id);
-- "Which contracts has this customer (ever) been in?" lookups, incl. the Feign check from Listing.
CREATE INDEX idx_contract_tenant_customer ON contract_tenant(customer_id);

-- GUARANTEES: at most one currently-occupying row per (contract, customer); a customer may only
--   rejoin a contract after their previous row was closed with left_at.
-- DOES NOT GUARANTEE: that a customer occupies only one contract at a time. The spec rule
--   "một khách không được thuộc hai hợp đồng ACTIVE cùng lúc" spans contract.status in another
--   table and cannot be expressed as an index here; it must be enforced in the service under a lock.
CREATE UNIQUE INDEX uq_contract_tenant_active_customer
    ON contract_tenant(contract_id, customer_id) WHERE left_at IS NULL;

-- GUARANTEES: at most one current representative per contract.
-- DOES NOT GUARANTEE: that a contract HAS a representative (a contract with no tenant yet has none),
--   and does not stop the representative from being closed out — the spec rule "không rời được nếu là
--   đại diện" (transfer the role first) is application logic. Transferring the role must clear the old
--   flag before setting the new one inside a single transaction.
CREATE UNIQUE INDEX uq_contract_tenant_representative
    ON contract_tenant(contract_id) WHERE is_representative AND left_at IS NULL;
