-- Contract event stream revision. Consumers (properties-service occupant projection) require strict
-- per-contract ordering: sourceRevision must be exactly checkpoint + 1. Existing contracts start at 0
-- and are bumped under the contract row lock whenever an event is published.
ALTER TABLE contract ADD COLUMN revision BIGINT NOT NULL DEFAULT 0;

-- Outbox ordering. created_at alone cannot order two events written in the same transaction (and the
-- relay previously ordered by created_at only, leaving ties to the database). An identity-backed
-- sequence preserves insert order, which is the order the relay must publish in for the same key.
ALTER TABLE outbox_event ADD COLUMN sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX idx_outbox_unpublished_order ON outbox_event (sequence_no) WHERE published_at IS NULL;
