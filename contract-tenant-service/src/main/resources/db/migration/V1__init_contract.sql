-- Contract DRAFT storage. Cross-service IDs are scalar references; no cross-database foreign keys.
CREATE TABLE contract (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rental_request_id   BIGINT NOT NULL UNIQUE,
    room_id             BIGINT NOT NULL,
    building_id         BIGINT NOT NULL,
    customer_id         BIGINT NOT NULL,
    status              VARCHAR(20) NOT NULL,
    start_date          DATE NOT NULL,
    end_date            DATE,
    rent_amount         NUMERIC(15, 0) NOT NULL,
    deposit_amount      NUMERIC(15, 0),
    termination_reason  VARCHAR(1000),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT contract_status_check CHECK (status IN ('DRAFT', 'ACTIVE', 'TERMINATED', 'ENDED'))
);
