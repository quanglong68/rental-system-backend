-- ve hoa don tong qua invoice.room_invoice_id va dong thoi la cac share cua no.

CREATE TABLE room_invoice (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id      BIGINT NOT NULL,
    building_id  BIGINT NOT NULL,
    month        INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    year         INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 2100),
    total_amount DECIMAL(15, 0) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    paid_amount  DECIMAL(15, 0) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    rent_amount  DECIMAL(15, 2) NOT NULL DEFAULT 0 CHECK (rent_amount >= 0),
    electric_amount DECIMAL(15, 2) NOT NULL DEFAULT 0 CHECK (electric_amount >= 0),
    water_amount DECIMAL(15, 2) NOT NULL DEFAULT 0 CHECK (water_amount >= 0),
    service_amount DECIMAL(15, 2) NOT NULL DEFAULT 0 CHECK (service_amount >= 0),
    status       VARCHAR(20) NOT NULL DEFAULT 'UNPAID',
    issued_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_date     DATE NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_room_invoice_room_month UNIQUE (room_id, month, year),
    CONSTRAINT chk_room_invoice_status CHECK (status IN ('UNPAID', 'PARTIALLY_PAID', 'PAID', 'OVERDUE'))
);
CREATE INDEX idx_room_invoice_building_month ON room_invoice (building_id, year, month);

ALTER TABLE invoice ADD COLUMN room_invoice_id BIGINT REFERENCES room_invoice (id);
CREATE INDEX idx_invoice_room_invoice ON invoice (room_invoice_id);
-- Nguoi dai dien duoc xem so tien cac thanh vien khac trong hoa don tong.
ALTER TABLE invoice ADD COLUMN is_representative BOOLEAN NOT NULL DEFAULT FALSE;

-- Backfill cho du lieu da co: gom cac hoa don tung nguoi thanh hoa don tong theo phong/thang.
INSERT INTO room_invoice (room_id, building_id, month, year, total_amount, paid_amount, status,
                          issued_at, due_date)
SELECT room_id,
       building_id,
       month,
       year,
       SUM(total_amount),
       SUM(paid_amount),
       CASE
           WHEN SUM(paid_amount) >= SUM(total_amount) AND SUM(total_amount) > 0 THEN 'PAID'
           WHEN bool_or(status = 'OVERDUE') THEN 'OVERDUE'
           WHEN SUM(paid_amount) > 0 THEN 'PARTIALLY_PAID'
           ELSE 'UNPAID'
       END,
       MIN(issued_at),
       MIN(due_date)
FROM invoice
GROUP BY room_id, building_id, month, year;

UPDATE invoice i
SET room_invoice_id = r.id
FROM room_invoice r
WHERE r.room_id = i.room_id
  AND r.month = i.month
  AND r.year = i.year;

-- Tong hop cac khoan tu invoice_item cua cac share.
UPDATE room_invoice r
SET rent_amount = coalesce((
        SELECT SUM(it.amount) FROM invoice_item it JOIN invoice i ON i.id = it.invoice_id
        WHERE i.room_invoice_id = r.id AND it.item_type = 'RENT'), 0),
    electric_amount = coalesce((
        SELECT SUM(it.amount) FROM invoice_item it JOIN invoice i ON i.id = it.invoice_id
        WHERE i.room_invoice_id = r.id AND it.item_type = 'ELECTRIC'), 0),
    water_amount = coalesce((
        SELECT SUM(it.amount) FROM invoice_item it JOIN invoice i ON i.id = it.invoice_id
        WHERE i.room_invoice_id = r.id AND it.item_type = 'WATER'), 0),
    service_amount = coalesce((
        SELECT SUM(it.amount) FROM invoice_item it JOIN invoice i ON i.id = it.invoice_id
        WHERE i.room_invoice_id = r.id AND it.item_type IN ('SERVICE_SHARED', 'SERVICE_PERSONAL')), 0);
