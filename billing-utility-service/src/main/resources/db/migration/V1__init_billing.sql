-- V1: schema billing_db (docs muc 9.5). Chi Flyway tao bang, Hibernate ddl-auto=validate.
-- Moi service mot database rieng, tham chieu cheo bang ID (khong FK xuyen service).
-- Thoi gian TIMESTAMPTZ (UTC); date dung DATE; tien VND theo muc 8/11.

-- Ban sao nho hop dong de kiem tra + phan quyen theo toa nha (cap nhat tu ContractSigned/Renewed/Ended).
CREATE TABLE contract_info (
    contract_id  BIGINT PRIMARY KEY,
    room_id      BIGINT NOT NULL,
    building_id  BIGINT NOT NULL,
    status       VARCHAR(20) NOT NULL,
    start_date   DATE NOT NULL,
    end_date     DATE NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_contract_info_room ON contract_info (room_id);
CREATE INDEX idx_contract_info_building ON contract_info (building_id);

-- Loai tien ich: Dien, Nuoc; mot don gia co dinh cho moi loai (khong bac thang).
CREATE TABLE utility_type (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    unit        VARCHAR(20) NOT NULL,
    unit_price  DECIMAL(15, 2) NOT NULL CHECK (unit_price >= 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Dong ho theo phong + loai tien ich; moi phong mot dong ho active cho moi loai.
CREATE TABLE meter (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id         BIGINT NOT NULL,
    building_id     BIGINT NOT NULL,
    utility_type_id BIGINT NOT NULL REFERENCES utility_type (id),
    meter_code      VARCHAR(50),
    initial_index   DECIMAL(15, 2) NOT NULL DEFAULT 0 CHECK (initial_index >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_meter_room_utility UNIQUE (room_id, utility_type_id)
);
CREATE INDEX idx_meter_room ON meter (room_id);
CREATE INDEX idx_meter_building ON meter (building_id);

-- Chi so chot tung thang; moi dong ho moi thang mot dong.
CREATE TABLE meter_reading (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meter_id      BIGINT NOT NULL REFERENCES meter (id),
    month         INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    year          INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 2100),
    reading_date  DATE NOT NULL,
    prev_index    DECIMAL(15, 2) NOT NULL,
    current_index DECIMAL(15, 2) NOT NULL,
    consumption   DECIMAL(15, 2) NOT NULL,
    unit_price    DECIMAL(15, 2) NOT NULL,
    amount        DECIMAL(15, 2) NOT NULL,
    entered_by    BIGINT,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_reading_meter_month UNIQUE (meter_id, month, year),
    CONSTRAINT chk_reading_index CHECK (current_index >= prev_index)
);
CREATE INDEX idx_reading_meter ON meter_reading (meter_id);

-- Bang gia dich vu theo toa nha (Wifi, rac, gui xe...), don gia co dinh theo thang.
CREATE TABLE service (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL,
    name        VARCHAR(200) NOT NULL,
    unit        VARCHAR(20) NOT NULL DEFAULT 'month',
    unit_price  DECIMAL(15, 0) NOT NULL CHECK (unit_price >= 0),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_service_building ON service (building_id);

-- Dich vu gan hop dong: SHARED (chia theo dau nguoi) hoac PERSONAL (ai dang ky nguoi do tra).
CREATE TABLE contract_service (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id       BIGINT NOT NULL,
    service_id        BIGINT NOT NULL REFERENCES service (id),
    service_name      VARCHAR(200) NOT NULL,
    quantity          INTEGER NOT NULL DEFAULT 1 CHECK (quantity >= 1),
    usage_type        VARCHAR(20) NOT NULL,
    contract_tenant_id BIGINT,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_usage_type CHECK (usage_type IN ('SHARED', 'PERSONAL'))
);
CREATE INDEX idx_contract_service_contract ON contract_service (contract_id);

-- Hoa don: moi nguoi o mot hoa don rieng cho moi thang (docs muc 9.5, 11).
CREATE TABLE invoice (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_id        BIGINT NOT NULL,
    room_id            BIGINT NOT NULL,
    building_id        BIGINT NOT NULL,
    contract_tenant_id BIGINT NOT NULL,
    customer_id        BIGINT NOT NULL,
    month              INTEGER NOT NULL CHECK (month BETWEEN 1 AND 12),
    year               INTEGER NOT NULL CHECK (year BETWEEN 2000 AND 2100),
    total_amount       DECIMAL(15, 0) NOT NULL CHECK (total_amount >= 0),
    paid_amount        DECIMAL(15, 0) NOT NULL DEFAULT 0 CHECK (paid_amount >= 0),
    status             VARCHAR(20) NOT NULL DEFAULT 'UNPAID',
    issued_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    due_date           DATE NOT NULL,
    overdue_notified   BOOLEAN NOT NULL DEFAULT FALSE,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_invoice_tenant_month UNIQUE (contract_tenant_id, month, year),
    CONSTRAINT chk_invoice_status CHECK (status IN ('UNPAID', 'PARTIALLY_PAID', 'PAID', 'OVERDUE'))
);
CREATE INDEX idx_invoice_building_month ON invoice (building_id, year, month);
CREATE INDEX idx_invoice_customer ON invoice (customer_id);
CREATE INDEX idx_invoice_room ON invoice (room_id);

-- Dong hoa don. meter_reading_id la quan he nhieu-mot (mot chi so xuat hien trong
-- hoa don cua nhieu nguoi) (docs muc 9.5).
CREATE TABLE invoice_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id          BIGINT NOT NULL REFERENCES invoice (id) ON DELETE CASCADE,
    item_type           VARCHAR(20) NOT NULL,
    description         VARCHAR(500) NOT NULL,
    amount              DECIMAL(15, 2) NOT NULL,
    meter_reading_id    BIGINT REFERENCES meter_reading (id),
    contract_service_id BIGINT REFERENCES contract_service (id),
    CONSTRAINT chk_item_type CHECK (item_type IN ('RENT', 'ELECTRIC', 'WATER', 'SERVICE_SHARED', 'SERVICE_PERSONAL'))
);
CREATE INDEX idx_item_invoice ON invoice_item (invoice_id);

-- Thanh toan: staff ghi nhan tien mat (method mac dinh CASH; VNPay/MoMo giai doan sau).
CREATE TABLE payment (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  BIGINT NOT NULL REFERENCES invoice (id),
    amount_paid DECIMAL(15, 0) NOT NULL CHECK (amount_paid > 0),
    method      VARCHAR(20) NOT NULL DEFAULT 'CASH',
    paid_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    note        VARCHAR(500),
    recorded_by BIGINT NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_payment_invoice ON payment (invoice_id);

-- Transactional Outbox (docs muc 5.3).
CREATE TABLE outbox_event (
    id           UUID PRIMARY KEY,
    topic        VARCHAR(100) NOT NULL,
    event_key    VARCHAR(255) NOT NULL,
    event_type   VARCHAR(100) NOT NULL,
    payload      JSONB NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ
);
CREATE INDEX idx_outbox_unpublished ON outbox_event (created_at) WHERE published_at IS NULL;

-- Idempotent consumer (docs muc 5.3).
CREATE TABLE processed_event (
    event_id     UUID PRIMARY KEY,
    processed_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
